import type { HazardCategoryId, HazardSeverity } from './hazards';
import type { SafetyPolicy } from './policy';

/**
 * The lexical rules.
 *
 * Free text reaches players in three places: the description of a challenge,
 * the description of a bonus objective, and the name of a zone. There is no
 * structure in that text to check, so it is checked with rules that look for
 * specific words. Each rule is small, names the hazard category it belongs to,
 * and says in one sentence what it is for. They are meant to be read, argued
 * with, and tested one at a time.
 *
 * What these rules are and are not:
 *
 *  - They work on normalised text (see text.ts): lower case, no punctuation.
 *  - They match whole words and listed word forms, never fragments.
 *  - They do not understand sentences. "Stay away from the road" matches the
 *    road rule and is refused. That is a deliberate false positive: an
 *    instruction that has to mention a road is one a player may mishear.
 *  - They are not a complete list of dangerous things. An instruction can be
 *    unsafe without matching any of them. `allow` means "no rule matched", and
 *    nothing here should be read as proof that an instruction is safe.
 *
 * A rule may depend on the policy, so that a game which declared itself
 * contact-free is held to that.
 */

export interface LexicalRule {
  /** Stable id, reported in the violation. */
  readonly id: string;
  readonly hazard: HazardCategoryId;
  /** What the rule is for, as a sentence a host could be shown. */
  readonly explanation: string;
  readonly pattern: RegExp;
  /** Overrides the hazard category's severity for this rule. */
  readonly severity?: HazardSeverity;
  /** If present, the rule applies only when this returns true for the policy. */
  readonly when?: (policy: SafetyPolicy) => boolean;
}

/** A pattern matching any of the alternatives as whole words. */
function words(...alternatives: string[]): RegExp {
  return new RegExp(`\\b(?:${alternatives.join('|')})\\b`);
}

